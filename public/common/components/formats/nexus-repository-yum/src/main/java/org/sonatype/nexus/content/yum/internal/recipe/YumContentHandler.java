package org.sonatype.nexus.content.yum.internal.recipe;

import java.io.IOException;
import java.util.Locale;

import javax.annotation.Nonnull;
import jakarta.inject.Singleton;

import org.sonatype.goodies.common.ComponentSupport;
import org.sonatype.nexus.content.yum.YumContentFacet;
import org.sonatype.nexus.content.yum.YumMetadataFacet;
import org.sonatype.nexus.repository.Repository;
import org.sonatype.nexus.repository.http.HttpResponses;
import org.sonatype.nexus.repository.view.Context;
import org.sonatype.nexus.repository.view.Handler;
import org.sonatype.nexus.repository.view.Payload;
import org.sonatype.nexus.repository.view.Response;
import org.sonatype.nexus.repository.view.matchers.token.TokenMatcher;

import org.springframework.stereotype.Component;

import static com.google.common.base.Preconditions.checkState;
import static org.sonatype.nexus.repository.http.HttpMethods.DELETE;
import static org.sonatype.nexus.repository.http.HttpMethods.GET;
import static org.sonatype.nexus.repository.http.HttpMethods.HEAD;
import static org.sonatype.nexus.repository.http.HttpMethods.PUT;

/**
 * Hosted Yum handler: serves RPMs and generated metadata, accepts RPM uploads and deletes.
 */
@Component
@Singleton
public class YumContentHandler
    extends ComponentSupport
    implements Handler
{
  private static final String REPODATA = "repodata/";

  @Nonnull
  @Override
  public Response handle(@Nonnull final Context context) throws Exception {
    String path = contentPath(context);
    String method = context.getRequest().getAction();
    Repository repository = context.getRepository();

    log.debug("{} repository '{}' content-path: {}", method, repository.getName(), path);

    YumContentFacet storage = repository.facet(YumContentFacet.class);

    switch (method) {
      case HEAD:
      case GET: {
        if (isMetadataPath(path)) {
          repository.facet(YumMetadataFacet.class).ensureMetadata();
        }
        return storage.get(path)
            .map(HttpResponses::ok)
            .orElseGet(() -> HttpResponses.notFound(path));
      }

      case PUT: {
        if (isMetadataPath(path)) {
          return HttpResponses.badRequest("Yum metadata is generated by the repository and cannot be uploaded");
        }
        if (!path.toLowerCase(Locale.ROOT).endsWith(".rpm")) {
          return HttpResponses.badRequest("Only .rpm files can be uploaded to a Yum hosted repository");
        }
        Payload content = context.getRequest().getPayload();
        try {
          storage.putRpm(path, content);
        }
        catch (IOException e) {
          log.debug("Invalid RPM upload to repository {}: {}", repository.getName(), path, e);
          return HttpResponses.badRequest("Invalid RPM package: " + e.getMessage());
        }

        try {
          repository.facet(YumMetadataFacet.class).rebuild();
        }
        catch (IOException e) {
          // The package is stored; metadata is rebuilt lazily on the next repomd.xml request.
          log.warn("Uploaded {} but failed to rebuild Yum metadata for repository {}",
              path, repository.getName(), e);
        }
        return HttpResponses.created();
      }

      case DELETE: {
        if (isMetadataPath(path)) {
          return HttpResponses.badRequest("Yum metadata is generated by the repository and cannot be deleted directly");
        }
        if (!storage.delete(path)) {
          return HttpResponses.notFound(path);
        }
        try {
          repository.facet(YumMetadataFacet.class).rebuild();
        }
        catch (IOException e) {
          log.warn("Deleted {} but failed to rebuild Yum metadata for repository {}",
              path, repository.getName(), e);
        }
        return HttpResponses.noContent();
      }

      default:
        return HttpResponses.methodNotAllowed(method, GET, HEAD, PUT, DELETE);
    }
  }

  private static boolean isMetadataPath(final String path) {
    String normalized = path.startsWith("/") ? path.substring(1) : path;
    return normalized.startsWith(REPODATA);
  }

  @Nonnull
  private String contentPath(final Context context) {
    TokenMatcher.State state = context.getAttributes().require(TokenMatcher.State.class);
    String path = state.getTokens().get(YumRecipeSupport.PATH_NAME);
    checkState(path != null, "Missing token: path");
    return path;
  }
}
