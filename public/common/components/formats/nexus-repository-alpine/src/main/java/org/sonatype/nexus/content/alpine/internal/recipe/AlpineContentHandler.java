package org.sonatype.nexus.content.alpine.internal.recipe;

import java.io.IOException;
import java.util.List;
import java.util.Optional;

import javax.annotation.Nonnull;
import jakarta.inject.Singleton;

import org.sonatype.nexus.content.alpine.AlpineContentFacet;
import org.sonatype.nexus.repository.Repository;
import org.sonatype.nexus.repository.view.Content;
import org.sonatype.nexus.repository.view.Context;
import org.sonatype.nexus.repository.view.Handler;
import org.sonatype.nexus.repository.view.Request;
import org.sonatype.nexus.repository.view.Response;
import org.sonatype.nexus.repository.view.matchers.token.TokenMatcher;
import org.sonatype.nexus.repository.view.payloads.BytesPayload;

import org.springframework.stereotype.Component;

import static org.sonatype.nexus.repository.http.HttpMethods.DELETE;
import static org.sonatype.nexus.repository.http.HttpMethods.GET;
import static org.sonatype.nexus.repository.http.HttpMethods.HEAD;
import static org.sonatype.nexus.repository.http.HttpMethods.POST;
import static org.sonatype.nexus.repository.http.HttpMethods.PUT;
import static org.sonatype.nexus.repository.http.HttpResponses.badRequest;
import static org.sonatype.nexus.repository.http.HttpResponses.created;
import static org.sonatype.nexus.repository.http.HttpResponses.methodNotAllowed;
import static org.sonatype.nexus.repository.http.HttpResponses.noContent;
import static org.sonatype.nexus.repository.http.HttpResponses.notFound;
import static org.sonatype.nexus.repository.http.HttpResponses.ok;
import static org.sonatype.nexus.repository.view.ContentTypes.APPLICATION_OCTET_STREAM;

/**
 * Serves and accepts content of hosted Alpine repositories.
 *
 * <p>Any {@code .apk} uploaded with {@code PUT}/{@code POST} is validated and stored. The
 * {@code APKINDEX.tar.gz} of every directory is generated on demand from the stanzas kept with the
 * package assets, so it never goes stale after an upload or a delete.</p>
 */
@Component
@Singleton
public class AlpineContentHandler
    implements Handler
{
  @Nonnull
  @Override
  public Response handle(@Nonnull final Context context) throws Exception {
    String path = contentPath(context);
    String method = context.getRequest().getAction();

    Repository repository = context.getRepository();
    AlpineContentFacet storage = repository.facet(AlpineContentFacet.class);

    switch (method) {
      case HEAD:
      case GET:
        return get(storage, path);
      case POST:
      case PUT:
        return put(context, storage, path);
      case DELETE:
        return storage.delete(path) ? noContent() : notFound(path);
      default:
        return methodNotAllowed(method, GET, HEAD, POST, PUT, DELETE);
    }
  }

  private Response get(final AlpineContentFacet storage, final String path) throws IOException {
    if (isIndex(path)) {
      String directory = directoryOfIndex(path);
      List<String> entries = storage.indexEntries(directory);
      return ok(new BytesPayload(AlpineIndexBuilder.build(entries), APPLICATION_OCTET_STREAM));
    }
    Optional<Content> content = storage.get(path);
    if (content.isPresent()) {
      return ok(content.get());
    }
    return notFound(path);
  }

  private Response put(
      final Context context,
      final AlpineContentFacet storage,
      final String path) throws IOException
  {
    Request request = context.getRequest();
    if (isIndex(path)) {
      return badRequest("APKINDEX.tar.gz is generated by the repository and cannot be uploaded");
    }
    if (!path.endsWith(".apk")) {
      return badRequest("Alpine packages must be uploaded as .apk files");
    }
    if (request.getPayload() == null) {
      return badRequest("Missing package payload");
    }
    try {
      storage.putPackage(path, request.getPayload());
    }
    catch (IllegalArgumentException e) {
      return badRequest(e.getMessage());
    }
    return created();
  }

  static boolean isIndex(final String path) {
    return path.equals(AlpineIndexBuilder.INDEX_FILE_NAME) || path.endsWith("/" + AlpineIndexBuilder.INDEX_FILE_NAME);
  }

  /**
   * {@code /v3.20/main/x86_64/APKINDEX.tar.gz} belongs to {@code /v3.20/main/x86_64}.
   */
  static String directoryOfIndex(final String path) {
    String directory = path.substring(0, path.length() - AlpineIndexBuilder.INDEX_FILE_NAME.length());
    if (directory.endsWith("/")) {
      directory = directory.substring(0, directory.length() - 1);
    }
    return directory.isEmpty() ? "/" : directory;
  }

  @Nonnull
  private String contentPath(final Context context) {
    TokenMatcher.State state = context.getAttributes().require(TokenMatcher.State.class);
    String path = state.getTokens().get(AlpineRecipeSupport.PATH_NAME);
    if (path == null || path.isEmpty()) {
      return "/";
    }
    return path.startsWith("/") ? path : "/" + path;
  }
}
