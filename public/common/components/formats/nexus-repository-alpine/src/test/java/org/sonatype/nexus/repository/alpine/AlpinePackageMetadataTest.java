package org.sonatype.nexus.repository.alpine;

import java.io.ByteArrayInputStream;
import java.io.ByteArrayOutputStream;
import java.nio.charset.StandardCharsets;
import java.security.MessageDigest;
import java.util.Base64;
import java.util.zip.GZIPOutputStream;

import org.apache.commons.compress.archivers.tar.TarArchiveEntry;
import org.apache.commons.compress.archivers.tar.TarArchiveOutputStream;
import org.junit.jupiter.api.Test;

import static org.hamcrest.MatcherAssert.assertThat;
import static org.hamcrest.Matchers.equalTo;
import static org.hamcrest.Matchers.is;

class AlpinePackageMetadataTest
{
  private static final String PKGINFO = """
      # Generated by abuild 3.13.0-r3
      pkgname = musl
      pkgver = 1.2.5-r4
      pkgdesc = the musl c library (libc) implementation
      url = https://musl.libc.org/
      builddate = 1792598648
      packager = Buildozer <alpine-devel@lists.alpinelinux.org>
      size = 667648
      arch = x86_64
      origin = musl
      commit = cb3382a0eb89834b7845df246077b941982d712d
      maintainer = Natanael Copa <ncopa@alpinelinux.org>
      license = MIT
      depend = so:libc.musl-x86_64.so.1
      depend = /bin/sh
      provides = so:libc.musl-x86_64.so.1=1
      install_if = foo=1
      provider_priority = 10
      datahash = 0a163af5b9da656ef3dd3e9f39d66baf49d19e5fc5269b4126495e4d1948ee33
      """;

  @Test
  void readsPkginfoAndComputesApkIdentity() throws Exception {
    byte[] control = gzipMember(tar(".PKGINFO", PKGINFO));
    byte[] signature = gzipMember(tar(".SIGN.RSA.test.rsa.pub", "signature"));
    byte[] data = gzipMember(tar("lib/ld-musl-x86_64.so.1", "binary"));

    byte[] apk = concat(signature, control, data);

    AlpinePackageMetadata metadata = AlpinePackageMetadata.read(new ByteArrayInputStream(apk), apk.length);

    assertThat(metadata.getName(), equalTo("musl"));
    assertThat(metadata.getVersion(), equalTo("1.2.5-r4"));
    assertThat(metadata.getArch(), equalTo("x86_64"));
    assertThat(metadata.getFileSize(), is((long) apk.length));
    assertThat(metadata.getInstalledSize(), is(667648L));
    assertThat(metadata.getDescription(), equalTo("the musl c library (libc) implementation"));
    assertThat(metadata.getUrl(), equalTo("https://musl.libc.org/"));
    assertThat(metadata.getLicense(), equalTo("MIT"));
    assertThat(metadata.getOrigin(), equalTo("musl"));
    assertThat(metadata.getMaintainer(), equalTo("Natanael Copa <ncopa@alpinelinux.org>"));
    assertThat(metadata.getBuildTime(), is(1792598648L));
    assertThat(metadata.getCommit(), equalTo("cb3382a0eb89834b7845df246077b941982d712d"));
    assertThat(metadata.getProviderPriority(), is(10));
    assertThat(metadata.getDepends().size(), is(2));
    assertThat(metadata.getProvides().size(), is(1));
    assertThat(metadata.getInstallIf().size(), is(1));

    // the identity is the SHA1 of the compressed control member, as computed by apk-tools
    assertThat(metadata.getChecksum(), equalTo("Q1" + Base64.getEncoder().encodeToString(sha1(control))));
  }

  @Test
  void rendersIndexStanzaLikeApkTools() throws Exception {
    byte[] control = gzipMember(tar(".PKGINFO", PKGINFO));
    byte[] apk = concat(control, gzipMember(tar("data", "x")));

    String entry = AlpinePackageMetadata.read(new ByteArrayInputStream(apk), apk.length).toIndexEntry();

    assertThat(entry.startsWith("C:Q1"), is(true));
    assertThat(entry.contains("\nP:musl\n"), is(true));
    assertThat(entry.contains("\nV:1.2.5-r4\n"), is(true));
    assertThat(entry.contains("\nA:x86_64\n"), is(true));
    assertThat(entry.contains("\nS:" + apk.length + "\n"), is(true));
    assertThat(entry.contains("\nI:667648\n"), is(true));
    assertThat(entry.contains("\nT:the musl c library (libc) implementation\n"), is(true));
    assertThat(entry.contains("\nU:https://musl.libc.org/\n"), is(true));
    assertThat(entry.contains("\nL:MIT\n"), is(true));
    assertThat(entry.contains("\no:musl\n"), is(true));
    assertThat(entry.contains("\nm:Natanael Copa <ncopa@alpinelinux.org>\n"), is(true));
    assertThat(entry.contains("\nt:1792598648\n"), is(true));
    assertThat(entry.contains("\nc:cb3382a0eb89834b7845df246077b941982d712d\n"), is(true));
    assertThat(entry.contains("\nk:10\n"), is(true));
    assertThat(entry.contains("\nD:so:libc.musl-x86_64.so.1 /bin/sh\n"), is(true));
    assertThat(entry.contains("\np:so:libc.musl-x86_64.so.1=1\n"), is(true));
    assertThat(entry.contains("\ni:foo=1\n"), is(true));
    assertThat(entry.endsWith("\n\n"), is(true));
  }

  @Test
  void skipsPaxHeadersBeforePkginfo() throws Exception {
    ByteArrayOutputStream controlTar = new ByteArrayOutputStream();
    try (TarArchiveOutputStream tar = new TarArchiveOutputStream(controlTar)) {
      byte[] pax = "11 ctime=0\n11 atime=0\n".getBytes(StandardCharsets.UTF_8);
      TarArchiveEntry paxEntry = new TarArchiveEntry("./PaxHeaders/.PKGINFO");
      paxEntry.setSize(pax.length);
      paxEntry.setMode(0644);
      tar.putArchiveEntry(paxEntry);
      tar.write(pax);
      tar.closeArchiveEntry();

      byte[] pkginfo = PKGINFO.getBytes(StandardCharsets.UTF_8);
      TarArchiveEntry entry = new TarArchiveEntry(".PKGINFO");
      entry.setSize(pkginfo.length);
      entry.setMode(0644);
      tar.putArchiveEntry(entry);
      tar.write(pkginfo);
      tar.closeArchiveEntry();
      tar.finish();
    }

    byte[] control = gzipMember(controlTar.toByteArray());
    byte[] apk = concat(control, gzipMember(tar("data", "x")));

    AlpinePackageMetadata metadata = AlpinePackageMetadata.read(new ByteArrayInputStream(apk), apk.length);

    assertThat(metadata.getName(), equalTo("musl"));
    assertThat(metadata.getVersion(), equalTo("1.2.5-r4"));
    assertThat(metadata.getChecksum(), equalTo("Q1" + Base64.getEncoder().encodeToString(sha1(control))));
  }

  @Test
  void rejectsPayloadsThatAreNotApkV2() {
    try {
      AlpinePackageMetadata.read(new ByteArrayInputStream("not a package".getBytes(StandardCharsets.UTF_8)), 13);
      throw new AssertionError("expected IllegalArgumentException");
    }
    catch (Exception e) {
      assertThat(e instanceof IllegalArgumentException, is(true));
    }
  }

  private static byte[] tar(final String name, final String content) throws Exception {
    ByteArrayOutputStream bytes = new ByteArrayOutputStream();
    try (TarArchiveOutputStream tar = new TarArchiveOutputStream(bytes)) {
      byte[] data = content.getBytes(StandardCharsets.UTF_8);
      TarArchiveEntry entry = new TarArchiveEntry(name);
      entry.setSize(data.length);
      entry.setMode(0644);
      tar.putArchiveEntry(entry);
      tar.write(data);
      tar.closeArchiveEntry();
      tar.finish();
    }
    return bytes.toByteArray();
  }

  private static byte[] gzipMember(final byte[] content) throws Exception {
    ByteArrayOutputStream bytes = new ByteArrayOutputStream();
    try (GZIPOutputStream gzip = new GZIPOutputStream(bytes)) {
      gzip.write(content);
    }
    return bytes.toByteArray();
  }

  private static byte[] concat(final byte[]... parts) {
    ByteArrayOutputStream bytes = new ByteArrayOutputStream();
    for (byte[] part : parts) {
      bytes.write(part, 0, part.length);
    }
    return bytes.toByteArray();
  }

  private static byte[] sha1(final byte[] content) throws Exception {
    return MessageDigest.getInstance("SHA-1").digest(content);
  }
}
